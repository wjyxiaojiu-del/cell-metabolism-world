#!/usr/bin/env node
// Split data-compiled.js into core (21 pathways) and extended (34 pathways).
// Core is loaded synchronously; extended is preloaded asynchronously at runtime.
// Usage: node tools/split-compiled.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { CORE_STUDY_PATHWAY_SET } = require('../shared/contracts.js');

function loadData(file) {
  const context = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
  return context.window.METABOLIC_COMPILED;
}

function splitData(data) {
  const isCore = id => CORE_STUDY_PATHWAY_SET.has(id);
  const groupsOf = item => (Array.isArray(item.group) ? item.group : [item.group]);

  const coreReactions = [];
  const extReactions = [];
  const coreReactionIds = new Set();
  const coreEntityIds = new Set();
  for (const reaction of data.reactions || []) {
    if (groupsOf(reaction).some(isCore)) {
      coreReactions.push(reaction);
      coreReactionIds.add(reaction.id);
      coreEntityIds.add(reaction.from);
      coreEntityIds.add(reaction.to);
    } else {
      extReactions.push(reaction);
    }
  }

  const coreEntities = [];
  const extEntities = [];
  const coreEntityIdSet = new Set();
  for (const entity of data.entities || []) {
    if (groupsOf(entity).some(isCore) || coreEntityIds.has(entity.id)) {
      coreEntities.push(entity);
      coreEntityIdSet.add(entity.id);
    } else {
      extEntities.push(entity);
    }
  }
  const extEntityIdSet = new Set(extEntities.map(entity => entity.id));
  for (const reaction of extReactions) {
    for (const id of [reaction.from, reaction.to]) {
      if (!coreEntityIdSet.has(id) && !extEntityIdSet.has(id)) {
        const entity = (data.entities || []).find(candidate => candidate.id === id);
        if (entity) {
          extEntities.push(entity);
          extEntityIdSet.add(id);
        }
      }
    }
  }

  const corePathwayMeta = {};
  const extPathwayMeta = {};
  for (const [id, meta] of Object.entries(data.pathwayMeta || {})) {
    if (isCore(id)) corePathwayMeta[id] = meta;
    else extPathwayMeta[id] = meta;
  }

  const coreLayouts = {};
  const extLayouts = {};
  for (const [id, layout] of Object.entries(data.expertPathwayLayouts || {})) {
    if (isCore(id)) coreLayouts[id] = layout;
    else extLayouts[id] = layout;
  }

  const coreCatalog = [];
  const extCatalog = [];
  const coreCatalogKeys = new Set();
  for (const entry of data.participantCatalog || []) {
    const hasCore = (entry.pathwayIds || []).some(isCore);
    if (hasCore) {
      coreCatalog.push(entry);
      coreCatalogKeys.add(entry.key);
    } else if (!coreCatalogKeys.has(entry.key)) {
      extCatalog.push(entry);
    }
  }

  return {
    core: {
      entities: coreEntities,
      reactions: coreReactions,
      pathwayMeta: corePathwayMeta,
      participantCatalog: coreCatalog,
      expertPathwayLayouts: coreLayouts,
      expertMapGuides: data.expertMapGuides || {}
    },
    ext: {
      entities: extEntities,
      reactions: extReactions,
      pathwayMeta: extPathwayMeta,
      participantCatalog: extCatalog,
      expertPathwayLayouts: extLayouts,
      expertMapGuides: {}
    }
  };
}

function serialize(name, object) {
  return `window.${name} = ${JSON.stringify(object, null, 1)};\n`;
}

function writeSplitFiles(root) {
  const data = loadData(path.join(root, 'data-compiled.js'));
  const { core, ext } = splitData(data);
  const banner = '// Generated by tools/split-compiled.js — do not edit by hand.\n';
  fs.writeFileSync(
    path.join(root, 'data-compiled-core.js'),
    banner + serialize('METABOLIC_COMPILED', core),
    'utf8'
  );
  fs.writeFileSync(
    path.join(root, 'data-compiled-ext.js'),
    banner + serialize('METABOLIC_COMPILED_EXT', ext),
    'utf8'
  );
  return { core, ext };
}

module.exports = { splitData, writeSplitFiles };

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const { core, ext } = writeSplitFiles(root);
  console.log(`已写出 data-compiled-core.js (实体 ${core.entities.length} / 反应 ${core.reactions.length} / 通路 ${Object.keys(core.pathwayMeta).length})`);
  console.log(`已写出 data-compiled-ext.js (实体 ${ext.entities.length} / 反应 ${ext.reactions.length} / 通路 ${Object.keys(ext.pathwayMeta).length})`);
}
